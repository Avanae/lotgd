        }































        rawoutput('</tr>');































    }































    rawoutput('</table>');































}































function grand_exchange_cancel_offer(int $userId, int $offerId): void































{































    if ($userId <= 0 || $offerId <= 0) {































        return;































    }































    $offer = grand_exchange_load_offer($offerId);































    if (! $offer || (int) $offer['user_id'] !== $userId) {































        output('`$That offer could not be found or does not belong to you.`0`n');































        return;































    }































    if ($offer['status'] !== 'active') {































        output('`$That offer is no longer active.`0`n');































        return;































    }































    $connection = grand_exchange_begin_transaction();































    try {































        if ($offer['type'] === 'sell') {































            $itemsTable = Database::prefix(GRAND_EXCHANGE_TABLE_ITEMS);































            $sql = sprintf(































                'SELECT `specialvalue`, `sellvaluegold`, `sellvaluegems`, `charges`































                 FROM `%s`































                 WHERE `offer_id` = %d',































                $itemsTable,































                $offerId































            );































            $result = Database::query($sql);































            $rows = [];































            while ($row = Database::fetchAssoc($result)) {































                if (! is_array($row)) {































                    break;































                }































                $rows[] = $row;































            }































            $deleteSql = sprintf('DELETE FROM `%s` WHERE `offer_id` = %d', $itemsTable, $offerId);































            Database::query($deleteSql);































            grand_exchange_restore_inventory_items($userId, (int) $offer['item_id'], $rows);































        } else {































            global $session;































            $refundGold = (int) $offer['held_gold'];































            $refundGems = (int) $offer['held_gems'];































            $session['user']['gold'] += $refundGold;































            $session['user']['gems'] += $refundGems;































            $offer['held_gold'] = 0;































            $offer['held_gems'] = 0;































        }































        grand_exchange_update_offer_after_trade($offerId, 0, (int) $offer['held_gold'], (int) $offer['held_gems'], 'cancelled');































        grand_exchange_commit_transaction($connection);































        output('`@The offer has been cancelled.`0`n');































        debuglog(sprintf('Cancelled Grand Exchange offer %d.', $offerId));































    } catch (Throwable $throwable) {































        grand_exchange_rollback_transaction($connection);































        output('`$Unable to cancel the offer at this time.`0`n');































        Output::getInstance()->debug('Grand Exchange cancel error: ' . $throwable->getMessage());































    }































}































function grand_exchange_update_offer_after_trade(int $offerId, int $quantityRemaining, int $heldGold, int $heldGems, string $status): void































{































    $status = in_array($status, ['active', 'fulfilled', 'cancelled'], true) ? $status : 'active';































    $offersTable = Database::prefix(GRAND_EXCHANGE_TABLE_OFFERS);































    $statusEscaped = Database::escape($status);































    $sql = sprintf(































        "UPDATE `%s`































         SET `quantity_remaining` = %d,































             `held_gold` = %d,































             `held_gems` = %d,































             `status` = '%s',































             `updated_at` = NOW()































         WHERE `offer_id` = %d",































        $offersTable,































        max(0, $quantityRemaining),































        max(0, $heldGold),































        max(0, $heldGems),































        $statusEscaped,































        $offerId































    );































    Database::query($sql);































}































function grand_exchange_take_reserved_items(int $offerId, int $quantity): array































{































    if ($quantity <= 0) {































        return [];































    }































    $itemsTable = Database::prefix(GRAND_EXCHANGE_TABLE_ITEMS);































    $sql = sprintf(































        "SELECT `id`, `specialvalue`, `sellvaluegold`, `sellvaluegems`, `charges`































         FROM `%s`































         WHERE `offer_id` = %d































         ORDER BY `id` ASC































         LIMIT %d",































        $itemsTable,































        $offerId,































        $quantity































    );































    $result = Database::query($sql);































    $rows = [];































    while ($row = Database::fetchAssoc($result)) {































        if (! is_array($row)) {































            break;































        }































        $rows[] = $row;































    }































    if ($rows === []) {































        return [];































    }































    $ids = array_map(static fn ($row) => (int) ($row['id'] ?? 0), $rows);































    $ids = array_filter($ids, static fn ($id) => $id > 0);































    if ($ids === []) {































        return [];































    }































    $idList = implode(',', $ids);































    $deleteSql = sprintf("DELETE FROM `%s` WHERE `id` IN (%s)", $itemsTable, $idList);































    Database::query($deleteSql);































    if (Database::affectedRows() !== count($ids)) {































        throw new RuntimeException('Unable to reserve items for the trade.');































    }































    return $rows;































}































function grand_exchange_restore_reserved_items(int $offerId, array $rows): void































{































    if ($rows === []) {































        return;































    }































    $itemsTable = Database::prefix(GRAND_EXCHANGE_TABLE_ITEMS);































    foreach ($rows as $row) {































        if (! isset($row['specialvalue'])) {































            continue;































        }































        $special = Database::escape($row['specialvalue']);































        $sellGold = max(0, (int) ($row['sellvaluegold'] ?? 0));































        $sellGems = max(0, (int) ($row['sellvaluegems'] ?? 0));































        $charges = max(0, (int) ($row['charges'] ?? 0));































        $sql = sprintf(































            "INSERT INTO `%s` (`offer_id`, `specialvalue`, `sellvaluegold`, `sellvaluegems`, `charges`)































             VALUES (%d, '%s', %d, %d, %d)",































            $itemsTable,































            $offerId,































            $special,































            $sellGold,































            $sellGems,































            $charges































        );































        Database::query($sql);































    }































}































function grand_exchange_credit_player(int $userId, int $gold, int $gems): void































{































    if ($userId <= 0) {































        return;































    }































    if ($gold <= 0 && $gems <= 0) {































        return;































    }































    $accountsTable = Database::prefix('accounts');































    $sql = sprintf(































        "UPDATE `%s`































         SET `gold` = `gold` + %d,































             `gems` = `gems` + %d































         WHERE `acctid` = %d",































        $accountsTable,































        max(0, $gold),































        max(0, $gems),































        $userId































    );































    Database::query($sql);































    global $session;































    if (isset($session['user']['acctid']) && (int) $session['user']['acctid'] === $userId) {































        $session['user']['gold'] += $gold;































        $session['user']['gems'] += $gems;































    }































}































function grand_exchange_accept_sell_offer(int $buyerId, int $offerId, int $quantity): void































{































    global $session;































    if ($buyerId <= 0) {































        output('`$You must be logged in to buy items.`0`n');































        return;































    }































    $offer = grand_exchange_load_offer($offerId);































    if (! $offer || $offer['type'] !== 'sell' || $offer['status'] !== 'active') {































        output('`$That sell offer is no longer available.`0`n');































        return;































    }































    if ((int) $offer['user_id'] === $buyerId) {































        output('`$You cannot purchase your own sell offer.`0`n');































        return;































    }































    $available = (int) $offer['quantity_remaining'];































    if ($available <= 0) {































        output('`$That offer has already been fulfilled.`0`n');































        return;































    }































    $quantity = max(1, min($quantity, $available));































    $priceGold = (int) $offer['price_gold'];































    $priceGems = (int) $offer['price_gems'];































    $totalGold = $priceGold * $quantity;































    $totalGems = $priceGems * $quantity;































    if (($session['user']['gold'] ?? 0) < $totalGold || ($session['user']['gems'] ?? 0) < $totalGems) {































        output('`$You do not have enough gold or gems.`0`n');































        return;































    }































    $items = [];































    $connection = grand_exchange_begin_transaction();































    try {































        $items = grand_exchange_take_reserved_items($offerId, $quantity);































        if (count($items) !== $quantity) {































            throw new RuntimeException('The items were not available.');































        }































        $session['user']['gold'] -= $totalGold;































        $session['user']['gems'] -= $totalGems;































        $taxPercent = grand_exchange_get_tax_percent();































        $taxGold = $taxPercent > 0 ? (int) floor($totalGold * $taxPercent / 100) : 0;































        $taxGems = $taxPercent > 0 ? (int) floor($totalGems * $taxPercent / 100) : 0;































        $payoutGold = $totalGold - $taxGold;































        $payoutGems = $totalGems - $taxGems;































        grand_exchange_credit_player((int) $offer['user_id'], $payoutGold, $payoutGems);































        grand_exchange_ensure_inventory_library();































        foreach ($items as $row) {































            $result = add_item_by_id(































                (int) $offer['item_id'],































                1,































                $buyerId,































                $row['specialvalue'] ?? '',































                (int) ($row['sellvaluegold'] ?? 0),































                (int) ($row['sellvaluegems'] ?? 0),































                (int) ($row['charges'] ?? 0)































            );































            if (! $result) {































                throw new RuntimeException('Unable to add the purchased item to your inventory.');































            }































        }































        invalidatedatacache("inventory-user-$buyerId");































        $remaining = $available - $quantity;































        $status = $remaining <= 0 ? 'fulfilled' : 'active';































        grand_exchange_update_offer_after_trade($offerId, $remaining, (int) $offer['held_gold'], (int) $offer['held_gems'], $status);































        grand_exchange_commit_transaction($connection);































        output('`@You purchased the item(s) successfully.`0`n');































        debuglog(sprintf(































            'Bought %d x %s (offer %d) for %d gold and %d gems.',































            $quantity,































            $offer['item_name'],































            $offerId,































            $totalGold,































            $totalGems































        ));































        debuglog(sprintf(































            'Sold %d x %s via the Grand Exchange to %s.',































            $quantity,































            $offer['item_name'],































            $session['user']['name'] ?? 'an adventurer'































        ), (int) $offer['user_id']);































    } catch (Throwable $throwable) {































        grand_exchange_rollback_transaction($connection);































        grand_exchange_restore_reserved_items($offerId, $items);































        $session['user']['gold'] += $totalGold;































        $session['user']['gems'] += $totalGems;































        invalidatedatacache("inventory-user-$buyerId");































        output('`$The purchase could not be completed. Please try again.`0`n');































        Output::getInstance()->debug('Grand Exchange purchase error: ' . $throwable->getMessage());































    }































}































function grand_exchange_fulfill_buy_offer(int $sellerId, int $offerId, int $quantity): void































{































    global $session;































    if ($sellerId <= 0) {































        output('`$You must be logged in to fulfill buy offers.`0`n');































        return;































    }































    if (! grand_exchange_is_inventory_available()) {































        output('`$The inventory system is required to fulfill buy offers.`0`n');































        return;































    }































    $offer = grand_exchange_load_offer($offerId);































    if (! $offer || $offer['type'] !== 'buy' || $offer['status'] !== 'active') {































        output('`$That buy offer is no longer available.`0`n');































        return;































    }































    if ((int) $offer['user_id'] === $sellerId) {































        output('`$You cannot fulfill your own buy offer.`0`n');































        return;































    }































    $available = (int) $offer['quantity_remaining'];































    if ($available <= 0) {































        output('`$That offer has already been fulfilled.`0`n');































        return;































    }































    $quantity = max(1, min($quantity, $available));































    $availableInventory = grand_exchange_get_available_inventory_quantity($sellerId, (int) $offer['item_id']);































    if ($availableInventory < $quantity) {































        output('`$You only have %s unequipped items available to trade.`0`n', $availableInventory);































        return;































    }































    grand_exchange_ensure_inventory_library();































    $inventoryTable = Database::prefix('inventory');































    $sql = sprintf(































        "SELECT `specialvalue`, `sellvaluegold`, `sellvaluegems`, `charges`































         FROM `%s`































         WHERE `userid` = %d AND `itemid` = %d AND `equipped` = 0































         LIMIT %d",































        $inventoryTable,































        $sellerId,































        (int) $offer['item_id'],































        $quantity































    );































    $result = Database::query($sql);































    $rows = [];































    while ($row = Database::fetchAssoc($result)) {































        if (! is_array($row)) {































            break;































        }































        $rows[] = $row;































    }































    if (count($rows) < $quantity) {































        output('`$Unable to reserve enough items from your inventory.`0`n');































        return;































    }































    $connection = grand_exchange_begin_transaction();































    try {































        $deleteSql = sprintf(































            "DELETE FROM `%s`































             WHERE `userid` = %d AND `itemid` = %d AND `equipped` = 0































             LIMIT %d",































            $inventoryTable,































            $sellerId,































            (int) $offer['item_id'],































            $quantity































        );































        Database::query($deleteSql);































        if (Database::affectedRows() < $quantity) {































            throw new RuntimeException('Unable to remove items from your inventory.');































        }































        $buyerId = (int) $offer['user_id'];































        foreach ($rows as $row) {































            $resultInsert = add_item_by_id(































                (int) $offer['item_id'],































                1,































                $buyerId,































                $row['specialvalue'] ?? '',































                (int) ($row['sellvaluegold'] ?? 0),































                (int) ($row['sellvaluegems'] ?? 0),































                (int) ($row['charges'] ?? 0)































            );































            if (! $resultInsert) {































                throw new RuntimeException('Unable to deliver items to the buyer.');































            }































        }































        invalidatedatacache("inventory-user-$sellerId");































        invalidatedatacache("inventory-user-$buyerId");































        $priceGold = (int) $offer['price_gold'];































        $priceGems = (int) $offer['price_gems'];































        $totalGold = $priceGold * $quantity;































        $totalGems = $priceGems * $quantity;































        if ($totalGold > (int) $offer['held_gold'] || $totalGems > (int) $offer['held_gems']) {































            throw new RuntimeException('The buyer does not have enough escrowed funds.');































        }































        $taxPercent = grand_exchange_get_tax_percent();































        $taxGold = $taxPercent > 0 ? (int) floor($totalGold * $taxPercent / 100) : 0;































        $taxGems = $taxPercent > 0 ? (int) floor($totalGems * $taxPercent / 100) : 0;































        $payoutGold = $totalGold - $taxGold;































        $payoutGems = $totalGems - $taxGems;































        $session['user']['gold'] += $payoutGold;































        $session['user']['gems'] += $payoutGems;































        $remainingHeldGold = (int) $offer['held_gold'] - $totalGold;































        $remainingHeldGems = (int) $offer['held_gems'] - $totalGems;































        $remainingQuantity = $available - $quantity;































        $status = $remainingQuantity <= 0 ? 'fulfilled' : 'active';































        grand_exchange_update_offer_after_trade($offerId, $remainingQuantity, $remainingHeldGold, $remainingHeldGems, $status);































        grand_exchange_commit_transaction($connection);































        output('`@You completed the trade and received payment.`0`n');































        debuglog(sprintf(































            'Filled buy order %d with %d x %s for %d gold and %d gems.',































            $offerId,































            $quantity,































            $offer['item_name'],































            $totalGold,































            $totalGems































        ));































        debuglog(sprintf(































            'Grand Exchange buy offer %d received %d items from %s.',































            $offerId,































            $quantity,































            $session['user']['name'] ?? 'a seller'































        ), $buyerId);































    } catch (Throwable $throwable) {































        grand_exchange_rollback_transaction($connection);































        grand_exchange_restore_inventory_items($sellerId, (int) $offer['item_id'], $rows);































        output('`$The trade could not be completed. Your items were returned.`0`n');































        Output::getInstance()->debug('Grand Exchange fulfill error: ' . $throwable->getMessage());































    }































}































